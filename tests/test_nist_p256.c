void print_hex(const char *label, const uint8_t *s, uint32_t len)
{
	printf("%s (%u) : ", label, len);
	for (uint32_t i = 0; i < len; i++)
		printf("%02x", s[i]);
	printf("\n");
}

const char *verify_cmp(const uint8_t *a, const uint8_t *b, uint32_t len)
{
	return ecp_memcmp(a, b, len) ? "No" : "Yes";
}

const char *verify_ieq(int32_t r)
{
	return r ? "No" : "Yes";
}

void test_ecdh_p256_1(const struct ecdh_p256_1 *in, int32_t vec_n)
{
	static struct ecdh_p256_1 out;
	int32_t r;

	r = ecp_ecdh_p256_public_key(in->a_pri, out.a_pub);

	printf("[ecdh_p256_1] vec%d.a_pub -- %s %s\n", vec_n,
		verify_cmp(in->a_pub, out.a_pub, sizeof(in->a_pri)),
		verify_ieq(r));
	if (r || ecp_memcmp(in->a_pub, out.a_pub, sizeof(in->a_pub))) {
		print_hex("=> in.a_pub", in->a_pub, sizeof(in->a_pub));
		print_hex("=> out.a_pub", out.a_pub, sizeof(out.a_pub));
	}

	r = ecp_ecdh_p256_public_key(in->b_pri, out.b_pub);

	printf("[ecdh_p256_1] vec%d.b_pub -- %s %s\n", vec_n,
		verify_cmp(in->b_pub, out.b_pub, sizeof(in->b_pri)),
		verify_ieq(r));
	if (r || ecp_memcmp(in->a_pub, out.a_pub, sizeof(in->a_pub))) {
		print_hex("=> in.a_pub", in->a_pub, sizeof(in->a_pub));
		print_hex("=> out.a_pub", out.a_pub, sizeof(out.a_pub));
	}

	r = ecp_ecdh_p256_shared_key(in->a_pri, out.b_pub, out.shared_key);

	printf("[ecdh_p256_1] vec%d.shared_key @ a_pri,b_pub -- %s %s\n",
		vec_n, verify_cmp(in->shared_key, out.shared_key,
			sizeof(in->shared_key)),
		verify_ieq(r));
	if (r || ecp_memcmp(in->shared_key, out.shared_key,
			sizeof(in->shared_key))) {
		print_hex("=> in.shared_key",
			in->shared_key, sizeof(in->shared_key));
		print_hex("=> out.shared_key",
			out.shared_key, sizeof(out.shared_key));
	}

	r = ecp_ecdh_p256_shared_key(in->b_pri, out.a_pub, out.shared_key);

	printf("[ecdh_p256_1] vec%d.shared_key @ b_pri,a_pub -- %s %s\n",
		vec_n, verify_cmp(in->shared_key, out.shared_key,
			sizeof(in->shared_key)),
		verify_ieq(r));
	if (r || ecp_memcmp(in->shared_key, out.shared_key,
			sizeof(in->shared_key))) {
		print_hex("=> in.shared_key",
			in->shared_key, sizeof(in->shared_key));
		print_hex("=> out.shared_key",
			out.shared_key, sizeof(out.shared_key));
	}
}

void test_ecdsa_p256_1(const struct ecdsa_p256_1 *in, int32_t vec_n)
{
	static struct ecdsa_p256_1 out;
	int32_t r;

	r = ecp_ecdsa_p256_public_key(in->pri, out.pub);

	printf("[ecdsa_p256_1] vec%d.pub -- %s %s\n", vec_n,
		verify_cmp(in->pub, out.pub, sizeof(in->pri)),
		verify_ieq(r));
	if (ecp_memcmp(in->pub, out.pub, sizeof(in->pub))) {
		print_hex("=> in.pub", in->pub, sizeof(in->pub));
		print_hex("=> out.pub", out.pub, sizeof(out.pub));
	}

	r = ecp_ecdsa_p256_sign(in->pri, in->ran,
		in->msg, in->msg_len, out.sig);

	printf("[ecdsa_p256_1] vec%d.sig @ sign -- %s %s\n", vec_n,
		verify_cmp(in->sig, out.sig, sizeof(in->sig)),
		verify_ieq(r));
	if (r || ecp_memcmp(in->sig, out.sig, sizeof(in->sig))) {
		print_hex("=> in.sig", in->sig, sizeof(in->sig));
		print_hex("=> out.sig", out.sig, sizeof(out.sig));
	}

	r = ecp_ecdsa_p256_verify(out.pub, out.sig,
		in->msg, in->msg_len);

	printf("[ecdsa_p256_1] vec%d @ verify -- %s\n", vec_n,
		verify_ieq(r));
}

int main(void)
{
	for (int32_t i = 0; i < (sizeof(ecdh_p256_1_vec)
			/ sizeof(ecdh_p256_1_vec[0])); i++) {
		test_ecdh_p256_1(&ecdh_p256_1_vec[i], i);
	}

	for (int32_t i = 0; i < (sizeof(ecdsa_p256_1_vec)
			/ sizeof(ecdsa_p256_1_vec[0])); i++) {
		test_ecdsa_p256_1(&ecdsa_p256_1_vec[i], i);
	}

	return 0;
}
