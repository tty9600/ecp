void test_eddsa_ed25519_1(const struct eddsa_ed25519_1 *in, int32_t vec_n)
{
	static struct eddsa_ed25519_1 out;
	int32_t r;

	ecp_eddsa_ed25519_public_key(in->pri, out.pub);

	printf("[eddsa_ed25519_1] vec%d.pub -- %s\n", vec_n,
		verify_cmp(in->pub, out.pub, sizeof(in->pri)));
	if (ecp_memcmp(in->pub, out.pub, sizeof(in->pub))) {
		print_hex("=> in.pub", in->pub, sizeof(in->pub));
		print_hex("=> out.pub", out.pub, sizeof(out.pub));
	}

	ecp_eddsa_ed25519_sign(in->pri, out.pub,
		in->msg, in->msg_len, out.sig);

	printf("[eddsa_ed25519_1] vec%d.sig @ sign -- %s\n", vec_n,
		verify_cmp(in->sig, out.sig, sizeof(in->sig)));
	if (ecp_memcmp(in->sig, out.sig, sizeof(in->sig))) {
		print_hex("=> in.sig", in->sig, sizeof(in->sig));
		print_hex("=> out.sig", out.sig, sizeof(out.sig));
	}

	r = ecp_eddsa_ed25519_verify(out.pub, out.sig,
		in->msg, in->msg_len);

	printf("[eddsa_ed25519_1] vec%d @ verify -- %s\n", vec_n,
		verify_ieq(r));
}

